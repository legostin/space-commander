import { ShieldCheck } from "lucide-react";
import { call } from "../api";
import { useStore } from "../store";
import { Modal } from "./ui";

interface Step {
  label: string;
  text: React.ReactNode;
}

/**
 * Перед любым запросом прав показываем всю цепочку: что вы хотите сделать → что для этого
 * нужно → почему Windows это ограничивает → что именно сделает приложение → что будет без прав.
 */
export function ElevationDialog() {
  const ask = useStore((s) => s.elevation);
  const close = useStore((s) => s.askElevation);
  const priv = useStore((s) => s.priv);
  const startScan = useStore((s) => s.startScan);
  const toast = useStore((s) => s.toast);
  if (!ask) return null;

  const drive = ask.root ? ask.root.replace(/\\$/, "") : "C:";
  let title = "Зачем нужны права администратора";
  let steps: Step[] = [];

  if (ask.reason === "scan") {
    title = "Быстрое сканирование: зачем права администратора";
    steps = [
      { label: "Что вы хотите", text: <>Просканировать диск {drive} за секунды, а не за минуты.</> },
      {
        label: "Что для этого нужно",
        text: (
          <>
            Прочитать главную таблицу файлов NTFS (<code>$MFT</code>) напрямую с тома <code>\\.\{drive}</code>. В ней уже записаны имя, размер и
            папка каждого файла — не нужно открывать миллионы папок по одной.
          </>
        ),
      },
      {
        label: "Почему Windows это ограничивает",
        text: <>Прямое чтение тома видит данные в обход разрешений отдельных папок. Поэтому такой доступ Windows выдаёт только администраторам.</>,
      },
      {
        label: "Что сделает приложение",
        text: <>Откроет том только на чтение, прочитает таблицу и построит карту. На диск ничего не записывается, службы и драйверы не устанавливаются.</>,
      },
      {
        label: "Что будет без прав",
        text: <>Обычный режим: обход папок. Результат почти тот же, но первое сканирование большого диска заметно дольше, а папки, закрытые системой, останутся непрочитанными.</>,
      },
    ];
  } else if (ask.reason === "clean") {
    title = "Очистка системных папок: зачем права администратора";
    steps = [
      { label: "Что вы хотите", text: <>Очистить: {ask.what ?? "системные временные файлы"}.</> },
      { label: "Что для этого нужно", text: <>Перечислить и удалить файлы в папках, которые принадлежат Windows, а не вашей учётной записи.</> },
      {
        label: "Почему Windows это ограничивает",
        text: <>В этих папках хранятся данные системы и всех пользователей компьютера. Изменять их разрешено только администраторам — чтобы обычная программа не могла повредить систему.</>,
      },
      {
        label: "Что сделает приложение",
        text: <>Удалит только файлы из показанных в списке папок. Каждый путь виден заранее — раскройте строку правила. Занятые файлы пропускаются.</>,
      },
      { label: "Что будет без прав", text: <>Эти пункты останутся недоступными. Всё, что лежит в вашем профиле (кеши браузеров, приложений, инструментов разработки), чистится и так.</> },
    ];
  } else if (ask.reason === "task") {
    title = "Задача с системной очисткой: зачем права администратора";
    steps = [
      { label: "Что вы хотите", text: <>Чтобы задача по расписанию чистила и системные папки.</> },
      { label: "Что для этого нужно", text: <>Планировщик Windows должен запускать задачу с наивысшими правами. Создать такую задачу может только процесс, который сам запущен от администратора.</> },
      { label: "Почему Windows это ограничивает", text: <>Иначе любая программа могла бы тихо выдать себе права администратора через Планировщик.</> },
      { label: "Что сделает приложение", text: <>После перезапуска вы сможете сохранить задачу. Она будет выполнять только выбранные правила очистки и ничего больше.</> },
      { label: "Что будет без прав", text: <>Задача создаётся с обычными правами и чистит только ваш профиль.</> },
    ];
  } else {
    steps = [
      { label: "Что это даст", text: <>Быстрое сканирование через таблицу файлов, чтение папок, закрытых системой, и очистку системных временных файлов и обновлений.</> },
      { label: "Почему Windows это ограничивает", text: <>Эти действия затрагивают данные системы и других пользователей компьютера.</> },
      { label: "Что сделает приложение", text: <>Ничего само по себе: повышенные права используются только для действий, которые вы запускаете. Службы и автозапуск не устанавливаются.</> },
      { label: "Что будет без прав", text: <>Всё основное работает и так: карта диска, поиск, кеши приложений и браузеров, расписание для вашего профиля.</> },
    ];
  }

  const elevate = async () => {
    try {
      await call("relaunch_elevated", { scan: ask.reason === "scan" ? ask.root : null });
    } catch (e) {
      toast("info", "Права не выданы", String(e));
    }
    close(null);
  };

  return (
    <Modal
      title={
        <span className="row gap8">
          <ShieldCheck size={18} className="tone-sun" />
          {title}
        </span>
      }
      onClose={() => close(null)}
      wide
      footer={
        <>
          <button className="btn ghost" onClick={() => close(null)}>
            Не сейчас
          </button>
          {ask.reason === "scan" && ask.root && (
            <button
              className="btn"
              onClick={() => {
                close(null);
                void startScan(ask.root!, "walk");
              }}
            >
              Сканировать без прав
            </button>
          )}
          <button className="btn primary" onClick={elevate}>
            <ShieldCheck size={15} />
            Перезапустить с правами
          </button>
        </>
      }
    >
      <ol className="chain">
        {steps.map((s, i) => (
          <li key={i}>
            <span className="chain-n">{i + 1}</span>
            <div>
              <div className="chain-label">{s.label}</div>
              <div className="chain-text">{s.text}</div>
            </div>
          </li>
        ))}
      </ol>
      <div className="note">
        Windows покажет своё окно подтверждения (UAC). Приложение перезапустится и сохранит повышенные права до закрытия.
        {priv?.elevation_type === 1 && " Ваша учётная запись не входит в администраторы — Windows попросит пароль администратора."}
      </div>
    </Modal>
  );
}
