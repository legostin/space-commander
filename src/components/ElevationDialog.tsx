import { ShieldCheck } from "lucide-react";
import { call } from "../api";
import { t } from "../i18n";
import { useStore } from "../store";
import { Modal } from "./ui";

/** Текст с фрагментами в обратных кавычках: они показываются моноширинным шрифтом. */
export function Rich({ text }: { text: string }) {
  return (
    <>
      {text.split("`").map((part, i) => (i % 2 ? <code key={i}>{part}</code> : part))}
    </>
  );
}

/**
 * Перед любым запросом прав показываем всю цепочку: что вы хотите сделать → что для этого
 * нужно → почему Windows это ограничивает → что именно сделает приложение → что будет без прав.
 */
export function ElevationDialog() {
  const ask = useStore((s) => s.elevation);
  const close = useStore((s) => s.askElevation);
  const priv = useStore((s) => s.priv);
  const startScan = useStore((s) => s.startScan);
  const toast = useStore((s) => s.toast);
  if (!ask) return null;

  const drive = ask.root ? ask.root.replace(/\\$/, "") : "C:";
  let title = t("Зачем нужны права администратора");
  let steps: [string, string][];

  if (ask.reason === "scan") {
    title = t("Быстрое сканирование: зачем права администратора");
    steps = [
      [t("Что вы хотите"), t("Просканировать диск {0} за секунды, а не за минуты.", drive)],
      [t("Что для этого нужно"), t("Прочитать главную таблицу файлов NTFS (`$MFT`) напрямую с тома `\\\\.\\{0}`. В ней уже записаны имя, размер и папка каждого файла — не нужно открывать миллионы папок по одной.", drive)],
      [t("Почему Windows это ограничивает"), t("Прямое чтение тома видит данные в обход разрешений отдельных папок. Поэтому такой доступ Windows выдаёт только администраторам.")],
      [t("Что сделает приложение"), t("Откроет том только на чтение, прочитает таблицу и построит карту. На диск ничего не записывается, службы и драйверы не устанавливаются.")],
      [t("Что будет без прав"), t("Обычный режим: обход папок. Результат почти тот же, но первое сканирование большого диска заметно дольше, а папки, закрытые системой, останутся непрочитанными.")],
    ];
  } else if (ask.reason === "clean") {
    title = t("Очистка системных папок: зачем права администратора");
    steps = [
      [t("Что вы хотите"), t("Очистить: {0}.", ask.what ?? t("системные временные файлы"))],
      [t("Что для этого нужно"), t("Перечислить и удалить файлы в папках, которые принадлежат Windows, а не вашей учётной записи.")],
      [t("Почему Windows это ограничивает"), t("В этих папках хранятся данные системы и всех пользователей компьютера. Изменять их разрешено только администраторам — чтобы обычная программа не могла повредить систему.")],
      [t("Что сделает приложение"), t("Удалит только файлы из показанных в списке папок. Каждый путь виден заранее — раскройте строку правила. Занятые файлы пропускаются.")],
      [t("Что будет без прав"), t("Эти пункты останутся недоступными. Всё, что лежит в вашем профиле (кеши браузеров, приложений, инструментов разработки), чистится и так.")],
    ];
  } else if (ask.reason === "task") {
    title = t("Задача с системной очисткой: зачем права администратора");
    steps = [
      [t("Что вы хотите"), t("Чтобы задача по расписанию чистила и системные папки.")],
      [t("Что для этого нужно"), t("Планировщик Windows должен запускать задачу с наивысшими правами. Создать такую задачу может только процесс, который сам запущен от администратора.")],
      [t("Почему Windows это ограничивает"), t("Иначе любая программа могла бы тихо выдать себе права администратора через Планировщик.")],
      [t("Что сделает приложение"), t("После перезапуска вы сможете сохранить задачу. Она будет выполнять только выбранные правила очистки и ничего больше.")],
      [t("Что будет без прав"), t("Задача создаётся с обычными правами и чистит только ваш профиль.")],
    ];
  } else {
    steps = [
      [t("Что это даст"), t("Быстрое сканирование через таблицу файлов, чтение папок, закрытых системой, и очистку системных временных файлов и обновлений.")],
      [t("Почему Windows это ограничивает"), t("Эти действия затрагивают данные системы и других пользователей компьютера.")],
      [t("Что сделает приложение"), t("Ничего само по себе: повышенные права используются только для действий, которые вы запускаете. Службы и автозапуск не устанавливаются.")],
      [t("Что будет без прав"), t("Всё основное работает и так: карта диска, поиск, кеши приложений и браузеров, расписание для вашего профиля.")],
    ];
  }

  const elevate = async () => {
    try {
      await call("relaunch_elevated", { scan: ask.reason === "scan" ? ask.root : null });
    } catch (e) {
      toast("info", t("Права не выданы"), String(e));
    }
    close(null);
  };

  return (
    <Modal
      title={
        <span className="row gap8">
          <ShieldCheck size={18} className="tone-sun" />
          {title}
        </span>
      }
      onClose={() => close(null)}
      wide
      footer={
        <>
          <button className="btn ghost" onClick={() => close(null)}>
            {t("Не сейчас")}
          </button>
          {ask.reason === "scan" && ask.root && (
            <button
              className="btn"
              onClick={() => {
                close(null);
                void startScan(ask.root!, "walk");
              }}
            >
              {t("Сканировать без прав")}
            </button>
          )}
          <button className="btn primary" onClick={elevate}>
            <ShieldCheck size={15} />
            {t("Перезапустить с правами")}
          </button>
        </>
      }
    >
      <ol className="chain">
        {steps.map(([label, text], i) => (
          <li key={i}>
            <span className="chain-n">{i + 1}</span>
            <div>
              <div className="chain-label">{label}</div>
              <div className="chain-text">
                <Rich text={text} />
              </div>
            </div>
          </li>
        ))}
      </ol>
      <div className="note">
        {t("Windows покажет своё окно подтверждения (UAC). Приложение перезапустится и сохранит повышенные права до закрытия.")}
        {priv?.elevation_type === 1 && ` ${t("Ваша учётная запись не входит в администраторы — Windows попросит пароль администратора.")}`}
      </div>
    </Modal>
  );
}
